def build_prompt(situation: str, counterpart: str, avoid: list | None = None, count: int = 10):
    s = SITUATIONS.get(situation, SITUATIONS["hoesik"])
    allergy = ", ".join([ALLERGIES[a] for a in (avoid or []) if a in ALLERGIES])
    allergy_line = f"\n- 피해야 할 주제(금지): {allergy}." if allergy else ""

    return f"""당신은 한국 직장인·일반인을 위한 스몰토크 전문가입니다.
상황: {s['label']} — {s['desc']}
상대 유형: {counterpart}
{allergy_line}
요구사항:
- 한국어로 정확히 {count}개의 대화 주제를 만들어 주세요.
- 각 주제는 다음 HTML 구조로 작성하세요:
  <div class="topic">
    <h3>주제 제목</h3>
    <p class="opener">이렇게 꺼내보세요: ~</p>
    <ul><li>후속 질문 1</li><li>후속 질문 2</li></ul>
  </div>
- 단답형 질문 금지. 상대가 이야기를 펼칠 수 있는 열린 주제로.
- 실제 입에 담을 수 있는 자연스러운 존댓말 멘트로 작성.
- 출력은 위 HTML 조각들만. 설명 없이."""


